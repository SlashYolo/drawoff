// Порядок «средних» сцен; из него берётся упорядоченная подвыборка нужной длины.
const middleOrder = ['companion', 'item', 'obstacle', 'antagonist', 'twist'];

function planBeats(rng, n) {
  if (n <= 1) return ['single'];
  if (n === 2) return ['intro', 'ending'];
  const middleCount = n - 3;
  const middle = middleOrder.slice();
  // Случайно выкидываем лишние средние сцены, сохраняя порядок.
  while (middle.length > middleCount) middle.splice(Math.floor(rng() * middle.length), 1);
  // Если игроков больше, чем сцен в плане, добавляем ещё препятствия.
  while (middle.length < middleCount) middle.splice(Math.max(1, middle.length - 1), 0, 'obstacle');
  return ['intro', ...middle, 'climax', 'ending'];
}

function generateProcedural(seed, n, rng = Math.random) {
  const s = seed;
  const h = s.hero;
  const plan = planBeats(rng, n);
  let lastObstacle = null;
  const pages = plan.map((beat) => {
    if (beat === 'single') {
      const a = pick(rng, beats.intro)(s);
      const b = pick(rng, beats.ending)(s);
      return { text: `${a.text} ${b.text}`, scene: a.scene };
    }
    // Повторные препятствия — разные: берём следующий шаблон.
    if (beat === 'obstacle' && lastObstacle !== null) {
      lastObstacle = (lastObstacle + 1) % beats.obstacle.length;
      return beats.obstacle[lastObstacle]({ ...s, obstacle: s.obstacle2 || s.obstacle });
    }
    const idx = Math.floor(rng() * beats[beat].length);
    if (beat === 'obstacle') lastObstacle = idx;
    return beats[beat][idx](s);
  });
  const titles = [
    `Сказание о том, как ${h.nom} ${v(h.g, 'отправился', 'отправилась', 'отправились')} ${s.goal.inf}`,
    `${cap(h.nom)} и ${s.companion.nom}`,
    `Летопись: ${s.setting.nom}`,
    `${cap(s.genre)}: ${s.item.nom}`,
  ];
  return { title: pick(rng, titles), pages, source: 'procedural' };
}

