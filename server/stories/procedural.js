// Окончание по роду: m — мужской, f — женский, p — мн. число, n — средний.
function v(g, m, f, p, n) {
  if (g === 'f') return f;
  if (g === 'p') return p;
  if (g === 'n') return n === undefined ? m : n;
  return m;
}

function cap(s) {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

function low(s) {
  return s.charAt(0).toLowerCase() + s.slice(1);
}

// «Когда …» — придаточное, после него нужна запятая.
function lead(time) {
  return /^Когда/.test(time) ? `${time},` : time;
}

// Причастный оборот в названии предмета закрываем запятой.
function closeClause(nom) {
  return nom.includes(',') ? `${nom},` : nom;
}

function pick(rng, arr) {
  return arr[Math.floor(rng() * arr.length)];
}

